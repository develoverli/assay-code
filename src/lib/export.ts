import { save } from "@tauri-apps/plugin-dialog";
import { writeTextFile } from "@tauri-apps/plugin-fs";
import type { Finding, Project, Severity } from "@/types";
import { SEVERITY_RANK } from "@/types";

/**
 * Findings out of Assay: SARIF for code scanning tools, Markdown for pull
 * requests. Each finding keeps the tool's own words plus the user's decision.
 */

export type ReportFormat = "sarif" | "markdown";

/** Rule id for a finding whose tool gave no category. */
const DEFAULT_RULE_ID = "finding";

/** SARIF has four levels; ours map onto them without pretending to be finer. */
const SARIF_LEVEL: Record<Severity, string> = {
  critical: "error",
  high: "error",
  medium: "warning",
  low: "note",
  info: "note",
};

const bySeverity = (a: Finding, b: Finding) =>
  SEVERITY_RANK[a.severity] - SEVERITY_RANK[b.severity] || (a.file ?? "").localeCompare(b.file ?? "");

/** A file path SARIF accepts: relative, forward slashes, no drive letter. */
function artifactUri(file: string): string {
  return file.replace(/\\/g, "/").replace(/^[A-Za-z]:\//, "").replace(/^\.\//, "");
}

function toSarif(project: Project, findings: Finding[], toolName: (id?: string | null) => string): string {
  const rules = new Map<string, { id: string; name: string }>();
  for (const f of findings) {
    const id = f.category ?? DEFAULT_RULE_ID;
    if (!rules.has(id)) rules.set(id, { id, name: id });
  }

  const results = findings.map((f) => ({
    ruleId: f.category ?? DEFAULT_RULE_ID,
    level: SARIF_LEVEL[f.severity],
    message: { text: f.message },
    ...(f.file
      ? {
          locations: [
            {
              physicalLocation: {
                artifactLocation: { uri: artifactUri(f.file) },
                ...(f.line ? { region: { startLine: f.line } } : {}),
              },
            },
          ],
        }
      : {}),
    // the triage decision travels with the finding, or it is lost in transit
    ...(f.status !== "open" ? { suppressions: [{ kind: "external", justification: f.status_reason ?? f.status }] } : {}),
    properties: {
      severity: f.severity,
      status: f.status,
      tool: toolName(f.tool_id),
      ...(f.status_reason ? { statusReason: f.status_reason } : {}),
    },
  }));

  const sarif = {
    $schema: "https://json.schemastore.org/sarif-2.1.0.json",
    version: "2.1.0",
    runs: [
      {
        tool: {
          driver: {
            name: "Assay",
            informationUri: "https://github.com/develoverli/assay-code",
            rules: [...rules.values()],
          },
        },
        // one logical run: several scanners, one project, as the user sees it
        automationDetails: { id: `assay/${project.name}` },
        results,
      },
    ],
  };
  return `${JSON.stringify(sarif, null, 2)}\n`;
}

/** One table cell: a `|` would end the cell and a line break the whole row. */
export function mdCell(text: string): string {
  return text.replace(/\|/g, "\\|").replace(/\r\n|\r|\n/g, "<br>");
}

/** The open findings as one Markdown table, most severe first. */
function openTable(open: Finding[], toolName: (id?: string | null) => string): string[] {
  const lines: string[] = [];
  lines.push("| Severity | Finding | Where | Tool |");
  lines.push("|---|---|---|---|");
  for (const f of [...open].sort(bySeverity)) {
    const at = f.line ? `:${f.line}` : "";
    const where = f.file ? `\`${mdCell(f.file)}${at}\`` : "_project_";
    lines.push(`| ${f.severity} | ${mdCell(f.message)} | ${where} | ${mdCell(toolName(f.tool_id))} |`);
  }
  return lines;
}

/** The triaged findings as a bullet list, with the reason the user gave. */
function triagedList(decided: Finding[]): string[] {
  const lines: string[] = [];
  for (const f of [...decided].sort(bySeverity)) {
    const at = f.line ? `:${f.line}` : "";
    const where = f.file ? ` (\`${f.file}${at}\`)` : "";
    const why = f.status_reason ? ` — _${f.status_reason}_` : "";
    lines.push(`- **${f.status}** — ${f.message}${where}${why}`);
  }
  return lines;
}

export function toMarkdown(
  project: Project,
  findings: Finding[],
  toolName: (id?: string | null) => string,
): string {
  const open = findings.filter((f) => f.status === "open");
  const decided = findings.filter((f) => f.status !== "open");
  const counts = new Map<Severity, number>();
  for (const f of open) counts.set(f.severity, (counts.get(f.severity) ?? 0) + 1);

  const lines: string[] = [];
  lines.push(`# ${project.name} — findings`);
  lines.push("");
  lines.push(
    `${open.length} open · ${decided.length} triaged · generated by Assay on ${new Date().toISOString().slice(0, 10)}`,
  );
  if (project.path) lines.push("");
  if (project.path) lines.push(`\`${project.path}\``);
  lines.push("");

  if (counts.size) {
    lines.push([...counts.entries()].map(([sv, n]) => `**${n}** ${sv}`).join(" · "));
    lines.push("");
  }

  if (open.length) {
    lines.push(...openTable(open, toolName));
    lines.push("");
  } else {
    lines.push("No open findings.");
    lines.push("");
  }

  if (decided.length) {
    lines.push("## Triaged");
    lines.push("");
    lines.push(...triagedList(decided));
    lines.push("");
  }

  return lines.join("\n");
}

/** File name that says what it is without the user having to type anything. */
function suggestedName(project: Project, format: ReportFormat): string {
  const slug = project.name.toLowerCase().replace(/[^a-z0-9]+/g, "-").replace(/^-|-$/g, "") || "project";
  const day = new Date().toISOString().slice(0, 10);
  return `assay-${slug}-${day}.${format === "sarif" ? "sarif" : "md"}`;
}

/**
 * Ask where to put the report and write it. Returns the path, or null when the
 * user closed the dialog.
 */
export async function saveReport(
  format: ReportFormat,
  project: Project,
  findings: Finding[],
  toolName: (id?: string | null) => string,
): Promise<string | null> {
  const path = await save({
    defaultPath: suggestedName(project, format),
    filters:
      format === "sarif"
        ? [{ name: "SARIF", extensions: ["sarif", "json"] }]
        : [{ name: "Markdown", extensions: ["md"] }],
  });
  if (!path) return null;
  const body = format === "sarif" ? toSarif(project, findings, toolName) : toMarkdown(project, findings, toolName);
  await writeTextFile(path, body);
  return path;
}
